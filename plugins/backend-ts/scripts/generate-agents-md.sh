#!/usr/bin/env bash
# Generate the Codex-facing catalog directly from skills/*/SKILL.md.
set -euo pipefail

MODE="write"
[ "${1:-}" = "--check" ] && MODE="check"

PLUGIN_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$PLUGIN_DIR/AGENTS.md"

extract_field() {
  local file="$1" field="$2"
  awk -v field="$field" '
    NR == 1 && $0 == "---" { fm=1; next }
    fm && $0 == "---" { exit }
    fm && index($0, field ":") == 1 {
      sub("^[^:]+:[[:space:]]*", "")
      print
      exit
    }
  ' "$file"
}

render() {
  echo '# backend-ts — Codex AGENTS.md'
  echo
  echo '> Generated from `skills/*/SKILL.md` by `scripts/generate-agents-md.sh`.'
  echo '> Do not edit this file directly.'
  echo
  echo '## 적용 규칙'
  echo
  echo '1. 실제 코드와 테스트, 프로젝트 `AGENTS.md`를 스킬보다 우선한다.'
  echo '2. 작업과 일치하는 스킬만 읽는다. 전체 스킬을 강제 로드하지 않는다.'
  echo '3. 오래된 심볼·경로·정책을 호환하지 말고 현재 구현으로 원자 교체한다.'
  echo
  echo '## Skills'
  echo
  echo '| Skill | Description |'
  echo '|---|---|'
  find "$PLUGIN_DIR/skills" -mindepth 2 -maxdepth 2 -name SKILL.md -print | sort | while IFS= read -r file; do
    name="$(extract_field "$file" name)"
    desc="$(extract_field "$file" description)"
    rel="skills/$name/SKILL.md"
    printf '| [`%s`](%s) | %s |\n' "$name" "$rel" "$desc"
  done
  echo
  echo '## 검증'
  echo
  echo '- `bash scripts/acceptance-check.sh` — 플러그인 구조와 생성물 검사'
  echo '- `bash scripts/audit-all.sh --project /path/to/repo` — API typecheck + lint'
  echo '- `bash scripts/audit-all.sh --project /path/to/repo --full` — API test + knip 포함'
}

if [ "$MODE" = "check" ]; then
  render
else
  render > "$OUT"
  echo "Generated: $OUT" >&2
fi
