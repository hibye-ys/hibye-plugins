#!/usr/bin/env node
// gen-hooks.mjs — Claude hook (hooks/hooks.json) 을 SoT 로 Codex / OpenCode 용
// 프로젝트-설치 아티팩트를 dist/ 에 생성한다.
//
// 설치 규약(setup-project.sh 와 일치): 훅 스크립트는 항상
//   <project>/.agents/hooks/<script>  에 위치한다 → 경로 비의존적 생성 가능.
//
// 생성물:
//   dist/claude/settings.hooks.json          ← <project>/.claude/settings.json 에 머지
//   dist/codex/hooks.json                     ← <project>/.codex/hooks.json
//   dist/opencode/plugins/<plugin>-hooks.js   ← <project>/.opencode/plugins/
//
// Usage:
//   node scripts/gen-hooks.mjs           # 생성
//   node scripts/gen-hooks.mjs --check   # drift 검증 (exit 1 on drift)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const PLUGIN_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const PLUGIN_NAME = basename(PLUGIN_DIR);
const SRC = join(PLUGIN_DIR, 'hooks', 'hooks.json');
const DIST = join(PLUGIN_DIR, 'dist');
const CHECK = process.argv.includes('--check');
const HOOK_SUBDIR = '.agents/hooks'; // 프로젝트 내 훅 스크립트 설치 경로 규약

// SoT 파싱: { hooks: { <Event>: [ { hooks: [ { command } ] } ] } }
const sot = JSON.parse(readFileSync(SRC, 'utf8'));
const events = Object.keys(sot.hooks || {});
if (events.length === 0) { console.error('gen-hooks: SoT 에 이벤트 없음'); process.exit(2); }

// command 에서 스크립트 파일명 추출 (…/hooks/<script>)
function scriptOf(event) {
  const entry = sot.hooks[event]?.[0]?.hooks?.[0]?.command || '';
  const m = /hooks\/([\w.\-]+)/.exec(entry);
  return m ? m[1] : null;
}
// 대표 스크립트 (전 이벤트 공통이라고 가정 — 본 plugin 은 SessionStart 1개)
const script = scriptOf(events[0]);
if (!script) { console.error('gen-hooks: command 에서 스크립트 경로 추출 실패'); process.exit(2); }

// ---- Claude: 프로젝트 settings.json 머지용 스니펫 ($CLAUDE_PROJECT_DIR 사용) ----
const claudeHooks = {};
for (const ev of events) {
  claudeHooks[ev] = [{ hooks: [{ type: 'command', command: `node "$CLAUDE_PROJECT_DIR/${HOOK_SUBDIR}/${script}"`, timeout: 5 }] }];
}
const claudeArtifact = JSON.stringify({ hooks: claudeHooks }, null, 2) + '\n';

// ---- Codex: <project>/.codex/hooks.json (repo-root 상대 경로) ----
const codexHooks = {};
for (const ev of events) {
  codexHooks[ev] = [{ matcher: 'startup|resume', hooks: [{ type: 'command', command: `node "${HOOK_SUBDIR}/${script}"` }] }];
}
const codexArtifact = JSON.stringify({ hooks: codexHooks }, null, 2) + '\n';

// ---- OpenCode: JS 플러그인 래퍼 (플러그인 파일 기준 상대 경로 → 경로 비의존) ----
const eventGuard = events
  .map((ev) => `"${ev}"`)
  .join(', ');
const openArtifact = `// Auto-generated by gen-hooks.mjs — ${PLUGIN_NAME} hook parity (do not edit).
// Claude/Codex 의 ${events.join(', ')} 훅과 동일한 스크립트를 OpenCode 세션 시작 시 실행.
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
// <project>/.opencode/plugins/ → <project>/${HOOK_SUBDIR}/${script}
const script = join(here, "..", "..", "${HOOK_SUBDIR}", "${script}");

export const ${PLUGIN_NAME.replace(/[^A-Za-z0-9]/g, '_')}_hooks = async () => ({
  event: async ({ event }) => {
    // OpenCode 세션 시작 계열 이벤트에서 스크립트 실행
    if (event?.type === "session.created" || event?.type === "session.start" || event?.type === "session.idle") {
      try { spawnSync("node", [script], { stdio: "inherit" }); } catch (_) { /* non-fatal */ }
    }
  },
});
`;

const targets = [
  { path: join(DIST, 'claude', 'settings.hooks.json'), content: claudeArtifact },
  { path: join(DIST, 'codex', 'hooks.json'), content: codexArtifact },
  { path: join(DIST, 'opencode', 'plugins', `${PLUGIN_NAME}-hooks.js`), content: openArtifact },
];

let drift = 0;
const written = [];
for (const t of targets) {
  const cur = existsSync(t.path) ? readFileSync(t.path, 'utf8') : null;
  if (cur === t.content) continue;
  if (CHECK) { console.error(`DRIFT: ${t.path.replace(PLUGIN_DIR + '/', '')}`); drift++; }
  else { mkdirSync(dirname(t.path), { recursive: true }); writeFileSync(t.path, t.content); written.push(t.path.replace(PLUGIN_DIR + '/', '')); }
}

if (CHECK) {
  if (drift > 0) { console.error(`gen-hooks: ${drift} file(s) out of date`); process.exit(1); }
  console.log('gen-hooks --check: OK');
} else {
  console.log(`gen-hooks: ${events.join(', ')} (script=${script}) → 3 formats (${written.length} written)`);
  for (const w of written) console.log(`  ${w}`);
}
